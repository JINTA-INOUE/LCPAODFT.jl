include("../src/LCPAODFT.jl")
using .LCPAODFT
using Test


@testset "XC_PBE" begin

    Exc = zeros(Float64, 2)
    DEXDD = zeros(Float64, 2)
    DECDD = zeros(Float64, 2)
    DEXDGD = zeros(Float64, 6)
    DECDGD = zeros(Float64, 6)

    ED = [0.1, 0.2]
    GDENS = [-0.1, 0.0, 0.7, 0.2, 0.4, -0.2]
    LCPAODFT.C_XC_PBE!(ED, GDENS, Exc, DEXDD, DECDD, DEXDGD, DECDGD)

    @test Exc ≈ [-0.5871499553734967, -0.03916863168900321]
    @test DEXDD ≈ [-0.5808204636570621, -0.6891729056585251]
    @test DECDD ≈ [-0.09481611949452337, -0.07153194417993645]
    @test DEXDGD ≈ [0.00347105480872407, -0.0, -0.024297383661068483, -0.009876868287808557, -0.019753736575617114, 0.009876868287808557]
    @test DECDGD ≈ [0.0020063562536092572, 0.008025425014437029, 0.010031781268046285, 0.0020063562536092572, 0.008025425014437029, 0.010031781268046285]
end