include("../src/LCPAODFT.jl")
using .LCPAODFT
using Test


@testset "LDA_CA" begin

    atol = 1.0e-15
    N = 10
    A = zeros(Float64, N)
    B = zeros(Float64, N)
    for i = 1:N
        A[i] = 0.1*i
    end

    @. B = LDA_CA(A, 0)
    Bref = [-0.396248202644766, -0.4902770642930487, -0.5556743477939751, -0.6075814698395103, -0.6513098705753037, -0.6894621356157502, -0.7235267011343955, -0.7544437653277025, -0.7828494743858213, -0.8091965682477968]
    @test isapprox(B, Bref, atol=atol)

    @. B = LDA_CA(A, 1)
    Bref = [-0.5175699503768498, -0.6413964500341135, -0.7278337858566857, -0.796548930367455, -0.8544452005172365, -0.9049660806033475, -0.9500803718510502, -0.9910315226685225, -1.0286607987729766, -1.0635669028892427]
    @test isapprox(B, Bref, atol=atol)

    @. B = LDA_CA(A, 2)
    Bref = [0.12132174773208382, 0.1511193857410648, 0.17215943806271064, 0.18896746052794466, 0.20313532994193284, 0.21550394498759726, 0.22655367071665464, 0.23658775734082, 0.2458113243871553, 0.25437033464144587]
    @test isapprox(B, Bref, atol=atol)

    @. B = LDA_CA(A, 3)
    Bref = [-1.2132174773208375, -0.7555969287053237, -0.5738647935423689, -0.4724186513198614, -0.40627065988386574, -0.35917324164599546, -0.32364810102379227, -0.295734696676025, -0.2731236937635059, -0.25437033464144587]
    @test isapprox(B, Bref, atol=atol)
end