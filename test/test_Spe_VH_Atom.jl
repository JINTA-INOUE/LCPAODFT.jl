include("../src/LCPAODFT.jl")
using .LCPAODFT
using Test


@testset "Spe_VH_Atom Si" begin
    verbosity = 0
    pao = Read_PAO(4.0, "Si", 7.0, "s2p2d1", ""; verbosity)
    pspot = Read_VPS("Si", "", "LDA", false; verbosity)

    Spe_VH_Atom = Calc_Spe_VH_Atom(pao, pspot)

    @test length(Spe_VH_Atom) == pspot.Spe_Num_Mesh_VPS+2
    @test Spe_VH_Atom[1:10] ≈ [2.1560674099659587, 2.1560673823984207, 2.156067354830882, 2.1560673696692354, 2.1560673647730715, 2.1560673813721087, 2.156067364918731, 2.1560673589503625, 2.156067392229625, 2.1560673548032847]
    @test Spe_VH_Atom[end-10:end] ≈ [0.1487766779755876, 0.1453874846098542, 0.14207546810574395, 0.1388388696742794, 0.1356760472092742, 0.13258528744961426, 0.12956491172249493, 0.1266133251871799, 0.1237290021173257, 0.12091038928029708, 0.11809177644326849]
end