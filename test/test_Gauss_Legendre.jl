include("../src/LCPAODFT.jl")
using .LCPAODFT
using Test


@testset "Gauss_Legendre" begin

    x, weight = Gauss_Legendre(1)
    @test x == [0.0]
    @test weight == [2.0]

    x, weight = Gauss_Legendre(2)
    @test x ≈ [-0.5773502691896257, 0.5773502691896257]
    @test weight ≈ [1.0, 1.0]

    x, weight = Gauss_Legendre(3)
    @test x ≈ [-0.7745966692414834, 0.0, 0.7745966692414834]
    @test weight ≈ [0.5555555555555555, 0.8888888888888888, 0.5555555555555555]

    x, weight = Gauss_Legendre(4)
    @test x ≈ [-0.8611363115940526, -0.3399810435848563, 0.3399810435848563, 0.8611363115940526]
    @test weight ≈ [0.3478548451374537, 0.6521451548625462, 0.6521451548625462, 0.3478548451374537]

    x, weight = Gauss_Legendre(5)
    @test x ≈ [-0.906179845938664, -0.5384693101056831, 0.0, 0.5384693101056831, 0.906179845938664]
    @test weight ≈ [0.236926885056189, 0.47862867049936647, 0.5688888888888889, 0.47862867049936647, 0.236926885056189]

    x, weight = Gauss_Legendre(6)
    @test x ≈ [-0.932469514203152, -0.6612093864662645, -0.23861918608319693, 0.23861918608319693, 0.6612093864662645, 0.932469514203152]
    @test weight ≈ [0.1713244923791705, 0.36076157304813855, 0.46791393457269126, 0.46791393457269126, 0.36076157304813855, 0.1713244923791705]
end