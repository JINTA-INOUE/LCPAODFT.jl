include("../src/LCPAODFT.jl")
using .LCPAODFT
using Test


@testset "LSDA_CA" begin

    N = 10
    A1 = zeros(Float64, N)
    A2 = zeros(Float64, N)
    B1 = zeros(Float64, N)
    B2 = zeros(Float64, N)
    for i = 1:N
        A1[i] = 0.1*i
        A2[i] = 0.1*i - 0.1
    end

    for i = 1:N
        B1[i], B2[i] = LSDA_CA(A1[i], A2[i], 0)
    end
    @test B1 ≈ [-0.46034093098153206, -0.5652592272569116, -0.655493177638245, -0.7259512914070506, -0.7844622891538316, -0.8349843636122684, -0.879750184156288, -0.9201450100349514, -0.9570910389993854, -0.9912355732956243]
    @test B2 ≈ [-0.46034093098153206, -0.5652592272569116, -0.655493177638245, -0.7259512914070506, -0.7844622891538316, -0.8349843636122684, -0.879750184156288, -0.9201450100349514, -0.9570910389993854, -0.9912355732956243]
    
    for i = 1:N
        B1[i], B2[i] = LSDA_CA(A1[i], A2[i], 1)
    end
    @test B1 ≈ [-0.608009424724141, -0.7799602760165304, -0.8938392806261601, -0.982582561558481, -1.0567201772221249, -1.1211012134834963, -1.1784157856456714, -1.2303319460212825, -1.2779644130956145, -1.3220995585227477]
    @test B2 ≈ [-0.1937719598767928, -0.6636788204487873, -0.8098561386700439, -0.9145642639423575, -0.9985920124640733, -1.0698304115965205, -1.1322382091448477, -1.1881181248654944, -1.2389415985000072, -1.2857125911712388]
    
    for i = 1:N
        B1[i], B2[i] = LSDA_CA(A1[i], A2[i], 2)
    end
    @test B1 ≈ [0.14766849374260893, 0.21470104875961873, 0.23834610298791503, 0.2566312701514304, 0.2722578880682933, 0.28611684987122804, 0.2986656014893834, 0.31018693598633124, 0.3208733740962291, 0.3308639852271235]
    @test B2 ≈ [-0.26656897110473926, 0.09841959319187576, 0.1543629610317988, 0.1886129725353069, 0.2141297233102417, 0.23484604798425218, 0.2524880249885597, 0.26797311483054315, 0.28185055950062193, 0.2944770178756146]
end